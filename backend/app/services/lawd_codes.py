def resolve_lawd_cd(sido: Optional[str], sigungu: Optional[str]) -> List[str]:
    """(시도, 시군구) → molit LAWD_CD 리스트. 미매칭이면 빈 리스트."""
    if not sido:
        return []
    sido = _SIDO_ALIAS.get(sido.strip(), sido.strip())
    sigungu = (sigungu or "").strip()
    sido = normalize_sido(sido, sigungu)   # 온비드 병합 지역명(전남광주통합특별시) 환원
    if (sido, sigungu) in _MERGED_LAWD:    # 통합시 신규 코드(프리픽스 12) 우선 — 옛 29/46 대체
        return [_MERGED_LAWD[(sido, sigungu)]]
    if sido in SIDO_SINGLE:            # 세종 등
        return [SIDO_SINGLE[sido]]
    if (sido, sigungu) in MULTI_LAWD:  # 개편 레거시 등 복수코드 → 우선
        return MULTI_LAWD[(sido, sigungu)]
    code = SIGUNGU_LAWD.get((sido, sigungu))   # 정확 매칭
    if code:
        return [code]
    if " " in sigungu:                 # "수원시 장안구"/"화성시 만세구"(이상치)
        base = sigungu.split(" ")[0]
        code = SIGUNGU_LAWD.get((sido, base))  # 시 단독 코드(화성시 등)
        if code:
            return [code]
        if (sido, base) in CITY_PARTS:        # 구 분할 시 → 전체 구 집계
            return CITY_PARTS[(sido, base)]
    if (sido, sigungu) in CITY_PARTS:  # 단독 "수원시" → 전체 구 집계
        return CITY_PARTS[(sido, sigungu)]
    return []
